/// UD (Unreliable Datagram) Queue Pair with all associated resources:
/// CQ, memory regions, buffers, and the CQ poller thread.
pub const UdQueue = struct {
    /// The Queue Pair handle.
    qp: *c.ibv_qp,

    /// Extended Completion Queue shared by sends and receives (supports
    /// timestamps). One CQ keeps completions in one stream for the poller.
    cq: *c.ibv_cq_ex,

    /// Send slots: NUM_SEND_SLOTS slots of SLOT_SIZE bytes in one MR.
    send_bufs: BufferSet,

    /// Receive slots: NUM_RECV_SLOTS slots of SLOT_SIZE bytes in one MR.
    recv_bufs: BufferSet,

    /// Queue Pair Number assigned by the hardware.
    qpn: u32,

    /// Whether this queue uses software timestamps (true) or hardware
    /// timestamps (false). Determined at creation based on device capabilities.
    uses_sw_timestamps: bool,

    /// Role of this queue: Sender or Responder.
    queue_type: QueueType,

    /// Pointer to the event ring buffer where CQ completions are written.
    /// The ring is owned by the Go side and passed in during queue creation.
    event_ring: ?*ring.EventRing,

    /// Handle for the CQ poller thread that reads completions and pushes
    /// events into the event ring.
    cq_thread: ?std.Thread,

    /// Back-pointer to the parent device.
    device: *RdmaDevice,

    /// Per-slot Address Handle for an in-flight UD send, stored as a usize
    /// pointer (0 = none) so the sender and CQ poller can publish/take it
    /// atomically. The sender release-stores the AH before ibv_post_send
    /// and must not destroy it until the matching send completion: destroying
    /// an AH while a UD WR that references it is still outstanding is
    /// undefined (completion error or crash). The CQ poller takes the AH
    /// with an acq_rel swap in destroySendSlotAh(). Timed-out sends keep
    /// the slot (and AH) allocated until that late completion.
    send_slot_ah: [NUM_SEND_SLOTS]std.atomic.Value(usize),

    /// Per-slot state tracking for send buffers, stored atomically (as the
    /// SlotState enum's u8 tag). Slots are allocated by the sender thread via
    /// allocSendSlot() and freed by the CQ poller thread via freeSendSlot()
    /// once a send completion arrives, so the two threads access this array
    /// concurrently; the atomic access keeps that race-free.
    send_slot_states: [NUM_SEND_SLOTS]std.atomic.Value(u8),

    /// Per-slot SendSlotMode (as its u8 tag). Written with release ordering
    /// by the thread that posts the send, after send_slot_remote_qpn and the
    /// slot payload, and read with acquire ordering by the CQ poller when
    /// the completion arrives. Reset to Sync when the slot is reclaimed.
    send_slot_modes: [NUM_SEND_SLOTS]std.atomic.Value(u8),

    /// Destination QPN of the asynchronous ACK pair in each slot, so the CQ
    /// poller can post the staged second ACK. Valid only while the slot's
    /// mode is AsyncFirstAck; published by the release store of the mode.
    send_slot_remote_qpn: [NUM_SEND_SLOTS]u32,

    /// Asynchronous ACK pairs that did not complete: a first or second ACK
    /// whose completion reported an error, or a second ACK the CQ poller
    /// could not post. Monotonic; read by Go via
    /// rdma_queue_async_ack_failures().
    async_ack_failures: std.atomic.Value(u64),

    /// Per-slot state tracking for receive buffers.
    recv_slot_states: [NUM_RECV_SLOTS]SlotState,

    /// Whether the CQ poller thread should keep running. Set to false
    /// during queue destruction to signal the poller to exit.
    running: std.atomic.Value(bool),

    /// Completion channel the CQ is attached to, or null when the provider
    /// could not create one. Owned by the queue and destroyed after the CQ.
    comp_channel: ?*c.ibv_comp_channel,

    /// True when the CQ poller sleeps in poll() on comp_channel until the CQ
    /// raises an event (ibv_req_notify_cq). False when no channel exists or
    /// the provider refused to arm the CQ; the poller then busy-polls with a
    /// short sleep. Written only before the poller starts or by the poller
    /// itself.
    uses_cq_events: bool,

    /// eventfd used to wake the CQ poller out of poll() on shutdown, or -1.
    /// stopCqPollerThread() writes it after clearing `running`.
    wake_fd: i32,

    // ----- Send completion signaling (synchronous send path) -----
    //
    // These fields form a single-slot mailbox, not a queue. They assume
    // "one UdQueue is driven by at most one sender thread at a time" -- a
    // caller posts a send WR, then waits on waitSendCompletion() before
    // posting another. The mailbox is matched by wr_id (= sendWrId(slot)):
    // the CQ poller publishes the completed send's wr_id LAST, with
    // release ordering, after writing timestamp/status; the waiting sender
    // spins until it observes ITS OWN wr_id (acquire) and only then trusts
    // timestamp/status.
    //
    // wr_id matching is what makes a LATE completion harmless: if a send
    // times out, its slot is deliberately left allocated (not reused) until
    // its completion finally arrives, so a stale completion publishes a wr_id
    // that no current waiter is looking for and is simply ignored -- it can
    // no longer be misread as the next send's T2/status. Because there is a
    // single sender and a QP delivers send completions in post order, the
    // current send's completion is always the last to be published, so the
    // waiter reliably observes its own wr_id without needing to reset the
    // mailbox from the consumer side (which would risk a lost wakeup).
    //
    // Do not remove the "1 Queue = 1 sender at a time" contract without
    // replacing this mailbox with a per-request completion slot.

    /// wr_id (send slot index) of the most recently published send completion,
    /// or SEND_WR_ID_NONE if none is pending. Written LAST by the CQ poller
    /// with release ordering; read by the sender with acquire ordering. The
    /// sender resets it to SEND_WR_ID_NONE just before posting so a reused
    /// slot's previous completion value cannot false-match.
    send_completion_wr_id: std.atomic.Value(u64),

    /// Send completion timestamp (nanoseconds). Written by the CQ poller
    /// before send_completion_wr_id, read by the sender once it matches wr_id.
    send_completion_timestamp: std.atomic.Value(u64),

    /// Send completion status. 0 = success, nonzero = RDMA error code.
    /// Written by the CQ poller before send_completion_wr_id.
    send_completion_status: std.atomic.Value(i32),

    /// Resources a queue is built from; see queue.createQueue().
    pub const InitArgs = struct {
        qp: *c.ibv_qp,
        cq: *c.ibv_cq_ex,
        send_bufs: BufferSet,
        recv_bufs: BufferSet,
        uses_sw_timestamps: bool,
        queue_type: QueueType,
        event_ring: ?*ring.EventRing,
        device: *RdmaDevice,
        comp_channel: ?*c.ibv_comp_channel,
        wake_fd: i32,
    };

    /// A queue with every send slot free, no poller running, CQ events off
    /// and an empty mailbox.
    pub fn init(a: InitArgs) UdQueue {
        return UdQueue{
            .qp = a.qp,
            .cq = a.cq,
            .send_bufs = a.send_bufs,
            .recv_bufs = a.recv_bufs,
            .qpn = a.qp.qp_num,
            .uses_sw_timestamps = a.uses_sw_timestamps,
            .queue_type = a.queue_type,
            .event_ring = a.event_ring,
            .cq_thread = null,
            .device = a.device,
            .send_slot_ah = @splat(std.atomic.Value(usize).init(0)),
            .send_slot_states = @splat(std.atomic.Value(u8).init(@backingInt(SlotState.Free))),
            .send_slot_modes = @splat(std.atomic.Value(u8).init(@backingInt(SendSlotMode.Sync))),
            .send_slot_remote_qpn = @splat(0),
            .async_ack_failures = std.atomic.Value(u64).init(0),
            .recv_slot_states = @splat(SlotState.Free),
            .running = std.atomic.Value(bool).init(false),
            .comp_channel = a.comp_channel,
            .uses_cq_events = false,
            .wake_fd = a.wake_fd,
            .send_completion_wr_id = std.atomic.Value(u64).init(SEND_WR_ID_NONE),
            .send_completion_timestamp = std.atomic.Value(u64).init(0),
            .send_completion_status = std.atomic.Value(i32).init(0),
        };
    }

    /// Atomically allocate a free send slot, transitioning it from Free to
    /// InUse. Returns the slot index, or null if every slot is currently in
    /// use. Called from the sender thread. The CAS makes concurrent
    /// allocation safe and, combined with freeSendSlot() running on the CQ
    /// poller, keeps the send_slot_states array race-free.
    pub fn allocSendSlot(self: *UdQueue) ?u32 {
        for (0..NUM_SEND_SLOTS) |i| {
            const idx: u32 = @intCast(i);
            if (self.send_slot_states[idx].cmpxchgStrong(
                @backingInt(SlotState.Free),
                @backingInt(SlotState.InUse),
                .acq_rel,
                .monotonic,
            ) == null) {
                return idx;
            }
        }
        return null;
    }

    /// Mark a send slot Free so it can be reused. Called by the CQ poller when
    /// a send completion arrives (the sole reclaim point for a posted WR's
    /// slot, so a late post-timeout completion still returns its slot), and by
    /// the sender only for slots whose WR was never actually posted (early
    /// error paths).
    pub fn freeSendSlot(self: *UdQueue, slot_index: u32) void {
        if (slot_index < NUM_SEND_SLOTS) {
            self.send_slot_states[slot_index].store(@backingInt(SlotState.Free), .release);
        }
    }

    /// Store an AH on a send slot. Called by the sender after ibv_create_ah
    /// and before ibv_post_send. Release-ordered so a CQ thread that
    /// observes the later send completion also observes this pointer.
    pub fn setSendSlotAh(self: *UdQueue, slot_index: u32, ah: *c.ibv_ah) void {
        if (slot_index < NUM_SEND_SLOTS) {
            self.send_slot_ah[slot_index].store(@intFromPtr(ah), .release);
        }
    }

    /// Take and destroy the AH stored on a send slot, if any. The acq_rel
    /// swap makes a concurrent take (CQ completion vs post_send failure vs
    /// teardown) destroy the handle at most once. Called by the CQ poller
    /// on send completion, by the sender on post_send failure (the WR was
    /// never accepted), and at queue teardown after a successful QP destroy.
    pub fn destroySendSlotAh(self: *UdQueue, slot_index: u32) void {
        if (slot_index >= NUM_SEND_SLOTS) return;
        const ptr = self.send_slot_ah[slot_index].swap(0, .acq_rel);
        if (ptr == 0) return;
        const ah: *c.ibv_ah = @ptrFromInt(ptr);
        _ = c.ibv_destroy_ah(ah);
    }

    /// Load the AH stored on a send slot without taking ownership, or null.
    /// The CQ poller uses it to post an asynchronous pair's second ACK on the
    /// AH of its first ACK, which stays on the slot until the second
    /// completes.
    pub fn sendSlotAh(self: *UdQueue, slot_index: u32) ?*c.ibv_ah {
        if (slot_index >= NUM_SEND_SLOTS) return null;
        const ptr = self.send_slot_ah[slot_index].load(.acquire);
        if (ptr == 0) return null;
        return @ptrFromInt(ptr);
    }

    /// Set a send slot's SendSlotMode with release ordering (see
    /// send_slot_modes).
    pub fn setSendSlotMode(self: *UdQueue, slot_index: u32, mode: SendSlotMode) void {
        if (slot_index < NUM_SEND_SLOTS) {
            self.send_slot_modes[slot_index].store(@backingInt(mode), .release);
        }
    }

    /// Read a send slot's SendSlotMode with acquire ordering.
    pub fn sendSlotMode(self: *UdQueue, slot_index: u32) SendSlotMode {
        if (slot_index >= NUM_SEND_SLOTS) return .Sync;
        return @fromBackingInt(self.send_slot_modes[slot_index].load(.acquire));
    }

    /// Return a send slot to the free pool once no WR references it:
    /// destroy its AH, reset its mode to Sync, then mark it Free. The mode
    /// is reset before the slot becomes allocatable so the next sender
    /// never inherits an asynchronous mode. Called by the CQ poller on the
    /// slot's last completion and by the sender when ibv_post_send rejects
    /// the WR (the slot's only two release points).
    pub fn releaseSendSlot(self: *UdQueue, slot_index: u32) void {
        self.destroySendSlotAh(slot_index);
        self.setSendSlotMode(slot_index, .Sync);
        self.freeSendSlot(slot_index);
    }

    /// Destroy every remaining per-slot AH. Safe only after the CQ poller
    /// has stopped and ibv_destroy_qp has succeeded (no outstanding UD WRs).
    pub fn destroyAllSendSlotAhs(self: *UdQueue) void {
        for (0..NUM_SEND_SLOTS) |i| {
            self.destroySendSlotAh(@intCast(i));
        }
    }
};

